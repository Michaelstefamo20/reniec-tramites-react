import { Router } from "express";
import rateLimit from "express-rate-limit";
import { accountSecurityController, cancelEmailChangeController, changePasswordController, confirmEmailChangeController, forgotPasswordController, loginController, logoutController, meController, registerController, requestEmailChangeController, resetPasswordController, setupPasswordController, verifyEmailController } from "../controllers/authController.js";
import { requireSession } from "../middleware/auth.js";
import { getPreferencesController, setPreferencesController } from "../controllers/preferencesController.js";
import { addFamilyController, listFamilyController, removeFamilyController } from "../controllers/familyController.js";
import { completeTutorialController, getTutorialController } from "../controllers/tutorialController.js";
import { listNotificationsController, markAllNotificationsReadController, markNotificationReadController } from "../controllers/notificationController.js";

export const authRoutes = Router();
const limiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 10, standardHeaders: "draft-7", legacyHeaders: false, message: { error: "Demasiados intentos. Espera unos minutos y vuelve a probar." } });
authRoutes.use(limiter);
authRoutes.post("/register", registerController);
authRoutes.post("/setup-password", setupPasswordController);
authRoutes.post("/verify-email", verifyEmailController);
authRoutes.post("/login", loginController);
authRoutes.post("/forgot-password", forgotPasswordController);
authRoutes.post("/reset-password", resetPasswordController);
authRoutes.post("/confirm-email-change", confirmEmailChangeController);
authRoutes.get("/account-security", requireSession, accountSecurityController);
authRoutes.post("/change-password", requireSession, changePasswordController);
authRoutes.post("/change-email", requireSession, requestEmailChangeController);
authRoutes.delete("/change-email", requireSession, cancelEmailChangeController);
authRoutes.get("/me", requireSession, meController);
authRoutes.get("/preferences", requireSession, getPreferencesController);
authRoutes.put("/preferences", requireSession, setPreferencesController);
authRoutes.get("/family", requireSession, listFamilyController);
authRoutes.post("/family", requireSession, addFamilyController);
authRoutes.delete("/family/:id", requireSession, removeFamilyController);
authRoutes.get("/tutorial", requireSession, getTutorialController);
authRoutes.post("/tutorial", requireSession, completeTutorialController);
authRoutes.get("/notifications", requireSession, listNotificationsController);
authRoutes.post("/notifications/read-all", requireSession, markAllNotificationsReadController);
authRoutes.post("/notifications/:id/read", requireSession, markNotificationReadController);
authRoutes.post("/logout", logoutController);
